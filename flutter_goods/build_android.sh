#!/usr/bin/env bash
set -euo pipefail
build_root="$(cd "$(dirname "$0")" && pwd)"
read -r shared_url shared_commit < "$build_root/source.lock"
shared="${COOLMALL_FLUTTER_MODULE:-$build_root/.shared-source}"
if [[ -z "${COOLMALL_FLUTTER_MODULE:-}" ]]; then
  mkdir -p "$shared"
  [[ -d "$shared/.git" ]] || git -C "$shared" init -q
  if ! git -C "$shared" cat-file -e "$shared_commit^{commit}" 2>/dev/null; then
    git -C "$shared" fetch --no-tags --depth=1 "$shared_url" "$shared_commit"
  fi
fi
module="$build_root/.module"
source_stage=$(mktemp -d "$build_root/.shared-export.XXXXXX")
trap 'rm -rf "$source_stage"' EXIT
git -C "$shared" archive "$shared_commit" lib assets test pubspec.yaml pubspec.lock analysis_options.yaml |
  tar -x -C "$source_stage"
for entry in lib assets test; do
  mkdir -p "$module/$entry"
  rsync -a --delete "$source_stage/$entry/" "$module/$entry/"
done
cp "$source_stage"/{pubspec.yaml,pubspec.lock,analysis_options.yaml} "$module/"
cd "$module"
commit=6df80cc1ea425cde1bac7d0265407977221061df
mkdir -p vendor
source_repo="${FLUTTER_BOOST_SOURCE:-$build_root/vendor/upstream}"
if [[ ! -d "$source_repo" ]]; then
  git clone --depth 1 --branch 4.6.5 https://github.com/alibaba/flutter_boost.git "$source_repo"
fi
# Build a clean patched copy without modifying the upstream checkout.
staging=$(mktemp -d vendor/boost.XXXXXX)
trap 'rm -rf "$source_stage" "$staging"' EXIT
git -C "$source_repo" archive "$commit" LICENSE pubspec.yaml lib android ios ohos | tar -x -C "$staging"
(cd "$staging" && patch -s -p1 < "$build_root/../experiments/flutter-boost-4.6.5/boost-android.patch")
mkdir -p vendor/flutter_boost
rsync -a --delete "$staging/" vendor/flutter_boost/
PUB_HOSTED_URL=https://pub.dev flutter pub get --enforce-lockfile "$@"
# The Flutter module wrapper is regenerated by pub get. Match the host toolchain.
python3 - <<'PY'
from pathlib import Path
import re
p = Path('.android/settings.gradle')
s = p.read_text()
for plugin, version in [('com.android.library','9.0.1'), ('org.jetbrains.kotlin.android','2.3.10')]:
    s, n = re.subn(r'(id "' + re.escape(plugin) + r'" version ")[^"]+', r'\g<1>' + version, s)
    assert n == 1, plugin
p.write_text(s)
PY
flutter build aar --no-pub --no-profile --target-platform android-arm,android-arm64 --build-number 1.0
mkdir -p "$build_root/build/host/outputs/repo"
rsync -a --delete "$module/build/host/outputs/repo/" "$build_root/build/host/outputs/repo/"
